# Opens the database with row_factory set, so each row can be used like a dictionary in Python and in the templates.
def get_connection():
    connection = sqlite3.connect(os.path.join(BASE_DIR, 'finance_db', 'finance_tracker.db'))
    connection.row_factory = sqlite3.Row
    return connection

# Looks up one account by its id. If no account has that id, abort(404) stops and shows a "Not Found" page instead of crashing.
def get_account_or_404(connection, account_id):
    account = connection.execute("SELECT * FROM account WHERE id = ?", (account_id,)).fetchone()
    if account is None:
        connection.close()
        abort(404)
    return account

# Home page: lists every account and the total balance across all of them and SUM is done by SQL.
@app.route('/')
def home_page():
    connection = get_connection()
    accounts = connection.execute("SELECT * FROM account").fetchall()
    total_balance = connection.execute("SELECT COALESCE(SUM(balance), 0) FROM account").fetchone()[0]
    connection.close()
    return render_template('fiscal_home.html', accounts=accounts, total_balance=total_balance)

# Account page: one account's details, its goals, and its 5 newest transactions.
@app.route('/account/<int:account_id>')
def account_page(account_id):
    connection = get_connection()
    account = get_account_or_404(connection, account_id)
    goals = connection.execute("SELECT * FROM account_goal WHERE account_id = ?", (account_id,)).fetchall()
    # ORDER BY date DESC LIMIT 5 gets the 5 newest by date, not just the last 5 rows added.
    recent_transactions = connection.execute(
        "SELECT * FROM transactions WHERE account_id = ? ORDER BY date DESC LIMIT 5", (account_id,)).fetchall()
    connection.close()
    return render_template('fiscal_account.html', account=account, goals=goals, recent_transactions=recent_transactions)

# Checks the transaction form before anything is saved. It returns a list of error messages and the cleaned-up values, so the route only saves data that passed every check.
def validate_transaction(form, categories):
    errors = []
    cleaned = {}

    # Date is required, must be a real date, and can't be in the future.
    date_text = form.get('date', '').strip()
    if not date_text:
        errors.append("Date is required.")
    else:
        try:
            transaction_date = datetime.strptime(date_text, '%Y-%m-%d').date()
            if transaction_date > date.today():
                errors.append("Date can't be in the future.")
            cleaned['date'] = date_text
        except ValueError:
            errors.append("Date must be a valid date.")

    # Name is required, and no longer than 100 characters. strip() removes spaces so "   " counts as empty.
    name = form.get('name', '').strip()
    if not name:
        errors.append("Name is required.")
    elif len(name) > 100:
        errors.append("Name must be 100 characters or fewer.")
    cleaned['name'] = name

    # Amount must be a number greater than 0 and no more than 1,000,000. float() raises ValueError if it isn't a number.
    amount_text = form.get('amount', '').strip()
    try:
        amount = round(float(amount_text), 2)
        if amount <= 0:
            errors.append("Amount must be greater than 0.")
        elif amount > 1000000:
            errors.append("Amount can't be more than $1,000,000.")
        cleaned['amount'] = amount
    except ValueError:
        errors.append("Amount must be a number.")

    # Type means only these two values are allowed, so a tampered form can't send something else.
    transaction_type = form.get('transaction_type', '')
    if transaction_type not in ('deposit', 'withdrawal'):
        errors.append("Type must be Deposit or Withdrawal.")
    cleaned['transaction_type'] = transaction_type

    # Category must have one of the ids that actually exists in the categories table.
    valid_category_ids = [str(category['id']) for category in categories]
    category_id = form.get('categories_id', '')
    if category_id not in valid_category_ids:
        errors.append("Please choose a category.")
    else:
        cleaned['categories_id'] = int(category_id)

    return errors, cleaned

# Transactions page will have GET showing the page and POST handles the add-transaction form.
@app.route('/account/<int:account_id>/transactions', methods=['GET', 'POST'])
def transactions_page(account_id):
    connection = get_connection()
    account = get_account_or_404(connection, account_id)
    categories = connection.execute("SELECT * FROM categories").fetchall()
    errors = []
    form = {}

    if request.method == 'POST':
        form = request.form
        errors, cleaned = validate_transaction(form, categories)
        # It is only to save when there are no errors. Otherwise it will fall through and re-render the page with the error messages.
        if not errors:
            connection.execute(
                "INSERT INTO transactions (date, name, amount, is_recurring, transaction_type, account_id, categories_id) VALUES (?, ?, ?, ?, ?, ?, ?)",
                (cleaned['date'], cleaned['name'], cleaned['amount'], 0, cleaned['transaction_type'], account_id, cleaned['categories_id']))
            # Deposits add to the balance and withdrawals subtract from it.
            change = cleaned['amount'] if cleaned['transaction_type'] == 'deposit' else -cleaned['amount']
            connection.execute("UPDATE account SET balance = balance + ? WHERE id = ?", (change, account_id))
            connection.commit()
            connection.close()
            # Redirecting after a successful POST means refreshing the page won't submit the same transaction twice.
            return redirect(url_for('transactions_page', account_id=account_id))

    # The JOIN brings in each transaction's category name so the page can show it.
    transactions = connection.execute("""
        SELECT transactions.*, categories.category_name
        FROM transactions
        LEFT JOIN categories ON transactions.categories_id = categories.id
        WHERE transactions.account_id = ?
        ORDER BY transactions.date DESC
        """, (account_id,)).fetchall()
    connection.close()
    # 400 tells the browser the submitted data was bad; 200 is a normal page.
    status = 400 if errors else 200
    return render_template('fiscal_transaction.html', account=account, transactions=transactions,
                           categories=categories, errors=errors, form=form), status

